package main

import (
	"bytes"
	"fmt"
	"go/format"
	"strings"
)

// goGenerator emits the Go DTOs and message registries.
type goGenerator struct{}

func (goGenerator) Name() string { return "go" }

func (goGenerator) Generate(idl *IDL) ([]Output, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by protocolgen from ws.idl.json; DO NOT EDIT.\npackage protocol\n\n")
	for _, name := range idl.defNames() {
		if err := writeGoDef(&b, name, idl.Defs[name]); err != nil {
			return nil, err
		}
	}
	writeGoRegistry(&b, idl)
	formatted, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated Go: %w", err)
	}
	return []Output{{Name: "types.gen.go", Data: formatted}}, nil
}

func writeGoDef(b *bytes.Buffer, name string, s schema) error {
	switch s.Type {
	case "string":
		fmt.Fprintf(b, "type %s string\nconst (\n", name)
		for _, v := range s.Enum {
			fmt.Fprintf(b, "%s%s %s = %q\n", name, exported(v), name, v)
		}
		b.WriteString(")\n\n")
		return nil
	case "object":
		fmt.Fprintf(b, "type %s struct {\n", name)
	default:
		return unsupported("definition "+name, "type "+s.Type)
	}
	for _, p := range keys(s.Properties) {
		f := s.Properties[p]
		n := f.GoName
		if n == "" {
			n = exported(p)
		}
		tag := p
		if !contains(s.Required, p) {
			tag += ",omitempty"
		}
		t, err := goType(f)
		if err != nil {
			return fmt.Errorf("definition %s, property %s: %w", name, p, err)
		}
		fmt.Fprintf(b, "%s %s `json:%q`\n", n, t, tag)
	}
	b.WriteString("}\n\n")
	return nil
}

func writeGoRegistry(b *bytes.Buffer, idl *IDL) {
	b.WriteString("const (\n")
	for _, r := range idl.Requests {
		fmt.Fprintf(b, "Request%s = %q\n", r.GoName, r.Type)
	}
	for _, e := range idl.Events {
		fmt.Fprintf(b, "Event%s = %q\n", e.GoName, e.Type)
	}
	b.WriteString(")\n\nvar Requests = map[string]RequestSpec{\n")
	for _, r := range idl.Requests {
		fmt.Fprintf(b, "%q: {Request: %q, Response: %q},\n", r.Type, r.Request, r.Response)
	}
	b.WriteString("}\n\nvar Events = map[string]string{\n")
	for _, e := range idl.Events {
		fmt.Fprintf(b, "%q: %q,\n", e.Type, e.Data)
	}
	b.WriteString("}\n")
}

func goType(s schema) (string, error) {
	if s.Ref != "" {
		return strings.TrimPrefix(s.Ref, "#/$defs/"), nil
	}
	if len(s.AnyOf) == 2 && s.AnyOf[1].Type == "null" {
		inner, err := goType(s.AnyOf[0])
		if err != nil {
			return "", err
		}
		return "*" + inner, nil
	}
	if s.Type == "array" {
		if s.Items == nil {
			return "", unsupported("array", "items")
		}
		item, err := goType(*s.Items)
		if err != nil {
			return "", err
		}
		return "[]" + item, nil
	}
	switch s.Type {
	case "string":
		return "string", nil
	case "integer":
		return "int64", nil
	case "number":
		return "float64", nil
	case "boolean":
		return "bool", nil
	default:
		return "", unsupported("field", "type "+s.Type)
	}
}
