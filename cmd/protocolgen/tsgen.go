package main

import (
	"bytes"
	"fmt"
	"strings"
)

// tsGenerator emits the TypeScript protocol types and message maps.
type tsGenerator struct{}

func (tsGenerator) Name() string { return "ts" }

func (tsGenerator) Generate(idl *IDL) ([]Output, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by protocolgen from ws.idl.json; DO NOT EDIT.\n// Numeric times and durations are milliseconds.\n\n")
	for _, name := range idl.defNames() {
		if err := writeTsDef(&b, name, idl.Defs[name]); err != nil {
			return nil, err
		}
	}
	writeTsMessageMaps(&b, idl)
	return []Output{{Name: "types.gen.ts", Data: b.Bytes()}}, nil
}

func writeTsDef(b *bytes.Buffer, name string, s schema) error {
	switch s.Type {
	case "string":
		fmt.Fprintf(b, "export type %s = %s\n\n", name, union(s.Enum))
		return nil
	case "object":
	default:
		return unsupported("definition "+name, "type "+s.Type)
	}
	// Discriminated alternatives (`anyOf` on an object) become an intersection
	// with a union of field subsets; the flattened base is exposed as NameFields.
	tsName := name
	if len(s.AnyOf) != 0 {
		tsName += "Fields"
	}
	if len(s.Properties) == 0 {
		fmt.Fprintf(b, "export type %s = Record<string, never>\n\n", tsName)
	} else {
		fmt.Fprintf(b, "export interface %s {\n", tsName)
		for _, p := range keys(s.Properties) {
			f := s.Properties[p]
			marker := ""
			if !contains(s.Required, p) {
				marker = "?"
			}
			t, err := tsType(f)
			if err != nil {
				return fmt.Errorf("definition %s, property %s: %w", name, p, err)
			}
			fmt.Fprintf(b, "  %s%s: %s\n", p, marker, t)
		}
		b.WriteString("}\n")
	}
	if len(s.AnyOf) != 0 {
		alternatives := make([]string, 0, len(s.AnyOf))
		for _, alternative := range s.AnyOf {
			if len(alternative.Required) == 0 {
				return unsupported("object anyOf in "+name, "alternative without required fields")
			}
			fields := make([]string, 0, len(alternative.Required))
			for _, required := range alternative.Required {
				t, err := tsType(s.Properties[required])
				if err != nil {
					return fmt.Errorf("definition %s: %w", name, err)
				}
				fields = append(fields, required+": "+t)
			}
			alternatives = append(alternatives, "{ "+strings.Join(fields, ", ")+" }")
		}
		fmt.Fprintf(b, "export type %s = %s & (%s)\n", name, tsName, strings.Join(alternatives, " | "))
	}
	b.WriteString("\n")
	return nil
}

func writeTsMessageMaps(b *bytes.Buffer, idl *IDL) {
	for _, group := range []string{"Request", "Response", "Event"} {
		fmt.Fprintf(b, "export interface %sDataMap {\n", group)
		if group == "Event" {
			for _, e := range idl.Events {
				fmt.Fprintf(b, "  %q: %s\n", e.Type, e.Data)
			}
		} else {
			for _, r := range idl.Requests {
				d := r.Request
				if group == "Response" {
					d = r.Response
				}
				fmt.Fprintf(b, "  %q: %s\n", r.Type, d)
			}
		}
		b.WriteString("}\n\n")
	}
	b.WriteString(`export type RequestType = keyof RequestDataMap
export type EventType = keyof EventDataMap
export type RequestMessage<T extends RequestType = RequestType> = {
  [K in T]: { version: 1, kind: 'request', type: K, requestId: string, data: RequestDataMap[K] }
}[T]
export type ResponseMessage<T extends RequestType = RequestType> = {
  [K in T]: { version: 1, kind: 'response', type: K, requestId: string } & (
    { data: ResponseDataMap[K], error?: never } | { data: Empty, error: Error }
  )
}[T]
export type EventMessage<T extends EventType = EventType> = {
  [K in T]: { version: 1, kind: 'event', type: K, data: EventDataMap[K] }
}[T]
export type ServerMessage = ResponseMessage | EventMessage
`)
}

func tsType(s schema) (string, error) {
	if s.Ref != "" {
		return strings.TrimPrefix(s.Ref, "#/$defs/"), nil
	}
	if len(s.AnyOf) == 2 && s.AnyOf[1].Type == "null" {
		inner, err := tsType(s.AnyOf[0])
		if err != nil {
			return "", err
		}
		return inner + " | null", nil
	}
	if s.Type == "array" {
		if s.Items == nil {
			return "", unsupported("array", "items")
		}
		item, err := tsType(*s.Items)
		if err != nil {
			return "", err
		}
		return item + "[]", nil
	}
	switch s.Type {
	case "string":
		return "string", nil
	case "integer", "number":
		return "number", nil
	case "boolean":
		return "boolean", nil
	default:
		return "", unsupported("field", "type "+s.Type)
	}
}

func union(values []string) string {
	quoted := make([]string, len(values))
	for i, v := range values {
		quoted[i] = fmt.Sprintf("%q", v)
	}
	return strings.Join(quoted, " | ")
}
